import path from 'node:path';
import { test, expect } from './fixtures.mjs';
import { configuracionInicial } from '../../shared/nueva-memoria.ts';
import { fontFixture } from '../font-fixture.ts';

test('estilo: guarda controles avanzados, importa fuentes y reutiliza una plantilla sin identidad @smoke', async ({ studio, page }, info) => {
  const config=configuracionInicial();config.datos.autor='Autora ficticia privada';config.datos.titulo='Memoria ficticia privada';
  await studio.json('/api/settings/init-memoria',{method:'POST',data:{dir:path.join(studio.root,'memoria-estilo'),configuracion:config}});
  await page.goto(studio.server.url);
  await page.getByRole('navigation',{name:'Secciones'}).getByRole('button',{name:'Memoria',exact:true}).click();
  await page.getByRole('tab',{name:'Apartados',exact:true}).click();
  await page.getByRole('tree',{name:'Estructura de la memoria'}).getByText('Datos del trabajo',{exact:true}).click();
  await page.getByText('Párrafos, títulos, listas y leyendas',{exact:true}).click();
  const space=page.getByLabel('Entre párrafos (pt)',{exact:true});await space.fill('6');await space.press('Tab');
  await page.getByLabel('Viñeta',{exact:true}).selectOption('guion');
  await page.getByLabel('Fuente del texto',{exact:true}).selectOption('schola');
  await expect.poll(async()=> (await studio.json('/api/memoria/datos')).institucion.espacioParrafo).toBe('6pt');
  await expect.poll(async()=> (await studio.json('/api/memoria/datos')).institucion.marcaLista).toBe('guion');
  await expect.poll(async()=> (await studio.json('/api/memoria/datos')).institucion.fuenteTexto).toBe('schola');
  await page.getByLabel('Archivos de fuentes',{exact:true}).setInputFiles({name:'fuente-ficticia.ttf',mimeType:'font/ttf',buffer:fontFixture()});
  await expect(page.getByText(/Familia ficticia: faltan/)).toBeVisible();
  await expect(page.getByLabel('Fuente del texto',{exact:true}).locator('option',{hasText:'Familia ficticia'})).toHaveCount(1);
  await page.getByRole('button',{name:'Componer portadas…',exact:true}).click();
  const cover=page.getByRole('dialog',{name:'Componer portadas',exact:true});
  await cover.getByRole('button',{name:'Seleccionar Título',exact:true}).click();
  await cover.getByLabel('Alineación del elemento',{exact:true}).selectOption('izquierda');
  await cover.getByLabel('Espacio después del elemento (mm)',{exact:true}).fill('8');
  await cover.getByRole('button',{name:'Guardar portadas',exact:true}).click();
  await expect.poll(async()=> (await studio.json('/api/memoria/portadas')).config.interior.find(b=>b.tipo==='titulo').espacio).toBe(8);
  await page.screenshot({path:info.outputPath('controles-estilo.png')});
  await page.getByRole('navigation',{name:'Secciones'}).getByRole('button',{name:'Ajustes',exact:true}).click();
  await page.getByRole('button',{name:'Guardar como plantilla…',exact:true}).click();
  const save=page.getByRole('dialog',{name:'Guardar como plantilla',exact:true});await save.getByLabel('Nombre',{exact:true}).fill('Estilo de prueba');
  await save.getByRole('button',{name:'Guardar plantilla',exact:true}).click();await expect(save).not.toBeVisible();
  const list=await studio.json('/api/templates/personal');expect(list.items).toHaveLength(1);
  const saved=await studio.json('/api/templates/personal/'+list.items[0].id);expect(saved.config.datos.autor).toBe('');expect(saved.config.institucion.espacioParrafo).toBe('6pt');
  const download=page.waitForEvent('download');await page.getByRole('link',{name:'Exportar ZIP',exact:true}).click();expect((await download).suggestedFilename()).toBe('plantilla.zip');
  await page.getByRole('button',{name:'Usar plantilla',exact:true}).click();const wizard=page.getByRole('dialog',{name:'Estilo de prueba',exact:true});
  await expect(wizard.getByLabel('Autor/a',{exact:true})).toHaveValue('');await expect(wizard.getByLabel('Título del trabajo',{exact:true})).toHaveValue('');
});
