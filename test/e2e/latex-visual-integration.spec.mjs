import fs from 'node:fs/promises';
import path from 'node:path';
import { test, expect } from './fixtures.mjs';

test('el editor visual convive con Notas, Multivista y Ajustes sin perder borradores @smoke', async ({ studio, page }) => {
  const file = path.join(studio.root, 'memoria/capitulo.tex');
  const source = '\\chapter{Capítulo ficticio}\\label{cap:ficticio}\n\nPárrafo original.\n';
  await fs.writeFile(file, source);
  await page.goto(studio.server.url);
  const nav = page.getByRole('navigation', { name: 'Secciones' });
  await nav.getByRole('button', { name: 'Buscar', exact: true }).click();
  const quick = page.getByRole('dialog', { name: 'Abrir o buscar' });
  await quick.getByLabel('Buscar', { exact: true }).fill('capitulo.tex');
  await quick.getByRole('option').filter({ hasText: 'capitulo.tex' }).first().click();
  const memory = page.getByRole('region', { name: 'Espacio: Memoria', exact: true });
  await memory.getByRole('button', { name: 'Visual', exact: true }).click();
  const visual = memory.getByRole('textbox', { name: 'Editor visual de LaTeX', exact: true });
  await expect(visual.locator('.et-visual-heading')).toHaveText('Capítulo ficticio');
  await visual.press('ControlOrMeta+End');
  await page.keyboard.insertText('Borrador visual ficticio');
  await nav.getByRole('button', { name: 'Notas', exact: true }).click();
  const notes = page.getByRole('region', { name: 'Espacio: Notas', exact: true });
  await notes.getByRole('treeitem', { name: 'Nota.md', exact: true }).click();
  await notes.getByRole('button', { name: /^Editar \(/ }).click();
  const note = notes.locator('.cm-content');
  await note.press('ControlOrMeta+End');
  await note.press('Enter');
  await page.keyboard.insertText('Borrador de nota ficticio');
  await nav.getByRole('button', { name: 'Multivista', exact: true }).click();
  await page.getByLabel('Apartado izquierdo', { exact: true }).selectOption('memoria');
  await page.getByLabel('Apartado derecho', { exact: true }).selectOption('notes');
  await expect(visual).toBeVisible();
  await expect(visual).toContainText('Borrador visual ficticio');
  await expect(note).toContainText('Borrador de nota ficticio');
  await nav.getByRole('button', { name: 'Ajustes', exact: true }).click();
  await page.getByRole('dialog', { name: 'Ajustes', exact: true }).getByRole('button', { name: 'Cerrar ajustes' }).click();
  await expect(visual).toContainText('Borrador visual ficticio');
  await expect(note).toContainText('Borrador de nota ficticio');
  await page.setViewportSize({ width: 900, height: 700 });
  await expect(memory.getByRole('button', { name: 'Código', exact: true })).toBeInViewport();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await memory.getByRole('button', { name: 'Código', exact: true }).click();
  const raw = memory.getByRole('textbox', { name: 'Editor de código', exact: true });
  await expect(raw).toContainText('\\label{cap:ficticio}');
  await expect(raw).toContainText('Borrador visual ficticio');
  await memory.getByRole('button', { name: 'Visual', exact: true }).click();
  await visual.press('ControlOrMeta+s');
  await expect.poll(() => fs.readFile(file, 'utf8')).toContain('Borrador visual ficticio');
  expect(await fs.readFile(file, 'utf8')).toContain('\\chapter{Capítulo ficticio}\\label{cap:ficticio}');
  expect(await fs.readFile(path.join(studio.root, 'notes/Nota.md'), 'utf8')).not.toContain('Borrador de nota ficticio');
});
