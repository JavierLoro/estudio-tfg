test('desde cero: diálogo estrecho, volver conserva la configuración y cancelar no crea archivos', async ({ studio, page }, info) => {
  const wizard = await start(studio, page);
  await page.setViewportSize({ width: 480, height: 850 });
  await wizard.getByLabel('Título del trabajo', { exact: true }).fill('No se debe crear');
  await wizard.getByRole('button', { name: 'Continuar', exact: true }).click();
  await wizard.getByLabel('Izquierdo', { exact: true }).fill('');
  await wizard.getByRole('button', { name: 'Continuar', exact: true }).click();
  await expect(wizard.getByRole('alert')).toContainText('Completa los cuatro márgenes');
  await wizard.getByLabel('Izquierdo', { exact: true }).fill('26');
  await wizard.getByRole('button', { name: 'Continuar', exact: true }).click();
  await expect(wizard.getByRole('heading', { name: 'Texto y títulos', exact: true })).toBeVisible();
  expect(await wizard.evaluate((el) => el.scrollWidth <= el.clientWidth)).toBe(true);
  await page.screenshot({ path: info.outputPath('tipografia-estrecha.png') });
  await wizard.getByText('Numeración, cabeceras y pies', { exact: true }).click();
  await wizard.getByLabel('Diseño de cabeceras y pies', { exact: true }).selectOption('personalizado');
  await wizard.getByLabel('Cabecera central', { exact: true }).selectOption('texto');
  await wizard.getByLabel('Texto de cabecera central', { exact: true }).fill('Texto que se conserva');
  await wizard.getByLabel('Texto de cabecera central', { exact: true }).scrollIntoViewIfNeeded();
  expect(await wizard.evaluate((el) => el.scrollWidth <= el.clientWidth)).toBe(true);
  await page.screenshot({ path: info.outputPath('paginacion-estrecha.png') });
  await wizard.getByLabel('Texto de cabecera central', { exact: true }).press('Tab');
  await wizard.getByRole('button', { name: 'Continuar', exact: true }).click();
  await wizard.getByText('Más opciones de índices y numeración', { exact: true }).click();
  await wizard.getByLabel('Mostrar en el índice general hasta', { exact: true }).scrollIntoViewIfNeeded();
  expect(await wizard.evaluate((el) => el.scrollWidth <= el.clientWidth)).toBe(true);
  await page.screenshot({ path: info.outputPath('indices-estrecho.png') });
  await wizard.getByRole('button', { name: 'Atrás', exact: true }).click();
  await wizard.getByRole('button', { name: 'Atrás', exact: true }).click();
  await expect(wizard.getByLabel('Izquierdo', { exact: true })).toHaveValue('26');
  await wizard.getByRole('button', { name: 'Atrás', exact: true }).click();
  await expect(wizard.getByLabel('Título del trabajo', { exact: true })).toHaveValue('No se debe crear');
  await wizard.getByRole('button', { name: 'Cancelar', exact: true }).click();
  expect((await studio.json('/api/settings')).values.memoriaDir).toBe(path.join(studio.root, 'memoria'));
  await expect(fs.stat(path.join(studio.root, 'mi-memoria'))).rejects.toMatchObject({ code: 'ENOENT' });
});
