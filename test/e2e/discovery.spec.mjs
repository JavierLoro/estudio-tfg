import { test, expect } from './fixtures.mjs';
const setup = async (page, studio) => {
  await page.route('**/api/desktop/setup', r => r.fulfill({ json: { needsSetup: false, engine: { phase: 'ready', available: true, installed: true, current: true } } }));
  await page.addInitScript(() => localStorage.setItem('et:chatgpt:welcome:cuenta-contexto-ficticia', 'true'));
  await studio.biblioteca();
  await page.getByRole('button', { name: 'Añadir', exact: true }).last().click();
  const dialog = page.getByRole('dialog', { name: 'Añadir a Biblioteca', exact: true });
  await dialog.getByRole('tab', { name: 'Buscar con asistente' }).click();
  const search = dialog.getByRole('region', { name: 'Buscar con asistente', exact: true });
  await expect(search.getByRole('checkbox', { name: 'Permitir búsquedas con esta cuenta para este proyecto' })).toBeEnabled();
  await search.getByRole('checkbox', { name: 'Permitir búsquedas con esta cuenta para este proyecto' }).click();
  await expect(search.getByRole('checkbox', { name: 'Permitir búsquedas con esta cuenta para este proyecto' })).toBeChecked();
  await search.getByLabel('Modelo de búsqueda').selectOption('modelo-contexto-ficticio');
  return { dialog, search };
};
for (const mode of ['quick', 'extended']) test(`búsqueda ${mode}, revisión y guardado elegido sin adjuntos ni altas automáticas @contexto`, async ({ studio, page }) => {
  const { dialog, search } = await setup(page, studio);
  await search.getByLabel('Necesidad de búsqueda').fill('Necesidad ficticia para el TFG');
  await search.getByLabel('Alcance de búsqueda').selectOption(mode);
  await search.getByRole('button', { name: 'Buscar fuentes', exact: true }).click();
  const tray = search.getByRole('region', { name: 'Bandeja de búsqueda', exact: true });
  await expect(tray.getByRole('button', { name: 'Guardar', exact: true }).first()).toBeEnabled();
  await expect(tray.getByText('Aportación inferida ficticia').first()).toBeVisible();
  expect((await studio.json('/api/resources')).items).toHaveLength(0);
  await dialog.getByRole('button', { name: 'Cerrar bandeja' }).click(); await page.reload();
  await page.getByRole('button', { name: 'Añadir', exact: true }).last().click();
  await dialog.getByRole('tab', { name: 'Buscar con asistente' }).click();
  await expect(search.getByLabel('Modelo de búsqueda')).toHaveValue('modelo-contexto-ficticio');
  await search.getByLabel('Consultas recientes').selectOption({ index: 1 });
  await expect(tray.getByRole('article')).toHaveCount(2);
  const article = tray.getByRole('article').filter({ has: page.getByRole('heading', { name: 'Artículo de búsqueda ficticio' }) });
  await article.getByRole('button', { name: 'Guardar', exact: true }).click();
  const review = page.getByRole('dialog', { name: 'Revisar incorporación a Biblioteca' });
  await review.getByLabel('Aportación del asistente', { exact: true }).fill('Nota de revisión elegida por la persona');
  await review.getByLabel('Colecciones (separadas por comas)').fill('Fuentes elegidas');
  await review.getByRole('button', { name: 'Guardar recurso elegido' }).click();
  await expect(review).not.toBeVisible();
  const [saved] = (await studio.json('/api/resources')).items;
  expect(saved.bibliography.fields.doi).toBe('10.1234/busqueda'); expect(saved.collections).toEqual(['Fuentes elegidas']);
  expect(saved.note).toContain('## Aportación del asistente'); expect(saved.note).toContain('Nota de revisión elegida por la persona'); expect(saved.attachments).toEqual([]);
  const web = tray.getByRole('article').filter({ has: page.getByRole('heading', { name: 'Web de búsqueda ficticia' }) });
  await web.getByRole('button', { name: 'Descartar', exact: true }).click(); await expect(web).toContainText('Descartado');
  expect((await studio.json('/api/resources')).items).toHaveLength(1);
});
